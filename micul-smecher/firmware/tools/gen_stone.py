#!/usr/bin/env python3
"""The MĂRGĂRITAR pebble for SoulOS Alive (os/DESIGN-ALIVE.md §2): the object's real front silhouette, baked
to a polygon table for the firmware's rasterizer.

    python3 tools/gen_stone.py        # writes lib/Suflet/src/StoneData.h

Source: renders/v9/src/marg_geo.py (the MĂRGĂRITAR v9 body). Its half-width w(z) is sampled at 30 heights from
the flat base cut (Z_CUT) to the crown on a cosine spacing (dense at the base corner and the domed top), in a unit
box (x / the widest width, y down, centred) — the same 30 points as the web's STONE table (os/index.html). The
outline (one side + its mirror) is smoothed like the web's stonePath(): Catmull-Rom as cubic Béziers with the
end points repeated (the flat base stays straight), sampled SUB points per segment.
Needs numpy (marg_geo.py). The firmware only reads the generated header.
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "lib", "Suflet", "src", "StoneData.h")
GEO = os.path.join(ROOT, "..", "renders", "v9", "src")
N = 30     # points on one side, base -> crown
SUB = 3    # samples per smoothed segment

# the web's table (os/index.html STONE), to check that both read the same shape
WEB = [(0.301, 0.5), (0.306, 0.497), (0.321, 0.488), (0.343, 0.474), (0.368, 0.454), (0.39, 0.428), (0.405, 0.398),
       (0.417, 0.363), (0.427, 0.324), (0.439, 0.281), (0.452, 0.234), (0.465, 0.185), (0.478, 0.134), (0.488, 0.081),
       (0.496, 0.027), (0.5, -0.027), (0.498, -0.081), (0.49, -0.134), (0.479, -0.185), (0.466, -0.234), (0.45, -0.281),
       (0.428, -0.324), (0.397, -0.363), (0.353, -0.398), (0.297, -0.428), (0.229, -0.454), (0.16, -0.474),
       (0.103, -0.488), (0.051, -0.497), (0.0, -0.5)]


def profile():
    sys.path.insert(0, os.path.abspath(GEO))
    import numpy as np
    import marg_geo as M
    B = M.geo()
    zz = np.linspace(M.Z_CUT, B.H, 20000)
    w = B.sections(zz)[0]
    W, H = 2 * float(w.max()), B.H - M.Z_CUT
    pts = []
    for i in range(N):
        t = (1 - math.cos(math.pi * i / (N - 1))) / 2
        pts.append((float(np.interp(M.Z_CUT + t * H, zz, w)) / W, 0.5 - t))
    pts[-1] = (0.0, -0.5)  # the crown is on the axis
    return pts, W / H


def smooth(P):
    out = [P[0]]
    for i in range(len(P) - 1):
        p0, p1, p2, p3 = P[max(0, i - 1)], P[i], P[i + 1], P[min(len(P) - 1, i + 2)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        for k in range(1, SUB + 1):
            t = k / SUB
            u = 1 - t
            out.append(tuple(u * u * u * p1[j] + 3 * u * u * t * c1[j] + 3 * u * t * t * c2[j] + t * t * t * p2[j] for j in range(2)))
    return out


def main():
    side, aspect = profile()
    dev = max(abs(a[0] - b[0]) + abs(a[1] - b[1]) for a, b in zip(side, WEB))
    if dev > 0.004:
        sys.exit(f"marg_geo.py and the web's STONE differ by {dev:.4f}: update one of them")
    full = side + [(-x, y) for x, y in reversed(side[:-1])]  # base right -> crown -> base left
    pts = smooth(full)  # base right -> crown -> base left; the polygon closes along the flat base
    lines = [
        "// GENERATED by tools/gen_stone.py from renders/v9/src/marg_geo.py - do not edit by hand.",
        "// The MĂRGĂRITAR's front silhouette (SoulOS Alive pebble), unit box: x in [-0.5, 0.5] (the widest",
        f"// width), y in [-0.5, 0.5] down (base at +0.5), centred. Body W:H = {aspect:.4f} (the pebble is drawn 90:101).",
        f"// {N} points per side on a cosine spacing, Catmull-Rom smoothed ({SUB} samples per segment) like stonePath().",
        "#pragma once",
        "",
        "namespace suflet {",
        "namespace stone {",
        f"static constexpr int kPoints = {len(pts)};",
        "static const float kXY[kPoints * 2] = {",
    ]
    for i in range(0, len(pts), 4):
        lines.append("    " + " ".join(f"{x:.5f}f, {y:.5f}f," for x, y in pts[i:i + 4]))
    lines += ["};", "}  // namespace stone", "}  // namespace suflet", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{len(pts)} points (max deviation from the web's table {dev:.4f}) -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
