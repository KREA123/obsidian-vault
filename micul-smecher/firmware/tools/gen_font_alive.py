#!/usr/bin/env python3
"""The SoulOS Alive type (os/DESIGN-ALIVE.md §2 / §8): the brand faces as anti-aliased glyph atlases.

    python3 tools/gen_font_alive.py      # writes lib/Suflet/src/FontAliveData.h

Bricolage Grotesque for every word, Martian Mono only for <= 2-word tags at 18 px+ (both SIL OFL 1.1:
tools/fonts/OFL-BricolageGrotesque.txt, OFL-MartianMono.txt; copied from brand/SOUL-Brand-Package/Fonts). The
variable fonts are set to each instance's axes (weight, optical size = the pixel size like the web's
font-optical-sizing: auto, width 100) by FreeType through Pillow, then rasterised exactly like tools/gen_font.py
(4-bit coverage, advances in 1/16 px, the FULL charset: ASCII + ă â î ș ț + the tray letters + typography, + ↑ ↓ →).
Nothing smaller than the 18 px type floor. Nunito (FontData.h) stays for the screens not yet moved to Alive.
"""
import os
import sys

from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_font as G  # noqa: E402  (raster(), pack4(), FULL)

ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "lib", "Suflet", "src", "FontAliveData.h")
BRIC = "BricolageGrotesque-VF.ttf"   # axes: opsz 12-96, wght 200-800, wdth 75-100
MONO = "MartianMono-VF.ttf"          # axes: wght 100-800, wdth 75-112

# + the arrows the screens use (the day's high / low ↑ ↓, a direction →): both faces have them, Nunito has not
ALIVE = G.FULL + "\u2191\u2193\u2192"

# name, file, px, weight, charset, what for
SIZES = [
    ("kFontTag", MONO, 18, 500, ALIVE, "<= 2-word tags: an AI's name, a rarity"),
    ("kFontSmall2", BRIC, 22, 600, ALIVE, "secondary lines, the dial's fact, speech, rim titles"),
    ("kFontBody", BRIC, 27, 500, ALIVE, "rows, body text"),
    ("kFontName", BRIC, 30, 700, ALIVE, "the dial's curved app name, titles"),
    ("kFontTitle", BRIC, 36, 700, ALIVE, "big titles, the callout"),
]


def load(file, px, wght):
    f = ImageFont.truetype(os.path.join(G.FONTS, file), px)
    vals = []
    for ax in f.get_variation_axes():
        n = ax["name"].decode() if isinstance(ax["name"], bytes) else ax["name"]
        if n.startswith("Weight"):
            vals.append(wght)
        elif n.startswith("Optical"):
            vals.append(max(ax["minimum"], min(ax["maximum"], px)))
        elif n.startswith("Width"):
            vals.append(100)
        else:
            vals.append(ax["default"])
    f.set_variation_by_axes(vals)
    return f


def main():
    lines = [
        "// GENERATED by tools/gen_font_alive.py - do not edit by hand.",
        "// Bricolage Grotesque (c) 2022 The Bricolage Grotesque Project Authors; Martian Mono (c) 2021 The Martian Mono",
        "// Project Authors. SIL Open Font License 1.1 (tools/fonts/OFL-*.txt). 4-bit anti-aliased coverage, rows packed",
        "// two pixels per byte (high nibble first), advances in 1/16 px (the format of FontData.h).",
        "#pragma once",
        '#include "Font.h"',
        "",
        "namespace suflet {",
        "namespace fontalive {",
        "",
    ]
    total, report = 0, []
    for name, file, px, wght, chars, why in SIZES:
        font = load(file, px, wght)
        asc, desc = font.getmetrics()
        glyphs, bits = [], bytearray()
        for cp in sorted(set(ord(c) for c in chars)):
            ch = chr(cp)
            w, h, ox, oy, data = G.raster(font, ch)
            adv16 = int(round(font.getlength(ch) * 16))
            if max(w, h) > 255 or not (-128 <= ox < 128 and -128 <= oy < 128):
                sys.exit(f"glyph {ch!r} at {px}px does not fit the table format")
            glyphs.append((cp, adv16, len(bits), w, h, ox, oy))
            bits += G.pack4(w, h, data)
        sym = name[len("kFont"):]
        face = "Martian Mono" if file == MONO else "Bricolage Grotesque"
        lines.append(f"// {face} {wght} {px}px ({why}): {len(glyphs)} glyphs, {len(bits)} B bitmap")
        lines.append(f"static const uint8_t k{sym}Bits[] = {{")
        for i in range(0, len(bits), 24):
            lines.append("    " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const Glyph k{sym}Glyphs[] = {{")
        for g in glyphs:
            lines.append("    {0x%04X, %d, %d, %d, %d, %d, %d}," % g)
        lines.append("};")
        lines.append(f"static const Font k{sym} = {{\"{face} {px}\", {px}, {asc}, {desc}, {int(round(px * 1.2))}, "
                     f"{len(glyphs)}, k{sym}Glyphs, k{sym}Bits}};")
        lines.append("")
        size = len(bits) + len(glyphs) * 12
        total += size
        report.append(f"  {name:12s} {face:20s} {wght} {px:3d}px {len(glyphs):4d} glyphs  {size / 1024:6.1f} KB")
    lines += ["}  // namespace fontalive", "}  // namespace suflet", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(report))
    print(f"  total flash  {total / 1024:.1f} KB -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
