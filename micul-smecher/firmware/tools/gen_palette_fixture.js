#!/usr/bin/env node
// Writes test/test_suflet/palette_fixture.h: the born palette the web SoulOS Alive computes (os/index.html,
// bornPalette(), DESIGN-ALIVE.md §2) for every one of the 120 designs x the 5 aluminium bodies. The native
// tests check that the firmware (lib/Suflet/src/Palette.cpp) gives the very same colours.
//
//   node tools/gen_palette_fixture.js      (run from firmware/)
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const E = require(path.resolve(root, '..', 'eyes', 'eyes.js'));
const designs = require(path.resolve(root, '..', 'eyes', 'designs.json')).designs;
const html = fs.readFileSync(path.resolve(root, '..', 'os', 'index.html'), 'utf8');

// the web's own code, cut out of the page: BODIES, COL and bornPalette (nothing re-typed here)
const a = html.indexOf('const BODIES = ['), b = html.indexOf('const LOOK = {', a);
if (a < 0 || b < 0) throw new Error('bornPalette not found in os/index.html');
const src = html.slice(a, b);
const clamp = (v, lo, hi) => (v < lo ? lo : v > hi ? hi : v);
const hex = (h) => { const n = parseInt(h.slice(1), 16); return [n >> 16 & 255, n >> 8 & 255, n & 255]; };
// eslint-disable-next-line no-new-func
const mk = new Function('EYES', 'clamp', 'hex', src + '\nreturn { BODIES, bornPalette };');
const { BODIES, bornPalette } = mk(E, clamp, hex);

const out = [];
const w = (s) => out.push(s);
const h = (s) => '0x' + s.slice(1).toUpperCase();
w('// GENERATED by tools/gen_palette_fixture.js from os/index.html bornPalette(). Do not edit.');
w('#pragma once');
w('#include <stdint.h>');
w('');
w('struct PaletteCase {');
w('  int16_t design;  // index into designs.json / kDesigns');
w('  uint8_t body;    // 0 Silver, 1 Graphite, 2 Midnight, 3 Ember, 4 Champagne');
w('  uint32_t e1, e2, b1, peb, peb2, pebe, on1, on2, onb;');
w('};');
w(`static const PaletteCase kPaletteCases[${designs.length * BODIES.length}] = {`);
designs.forEach((d, i) => BODIES.forEach((B, bi) => {
  const P = bornPalette(d, B.id);
  w(`    {${i}, ${bi}, ${[P.e1, P.e2, P.b1, P.peb, P.peb2, P.pebe, P.on1, P.on2, P.onb].map(h).join(', ')}},`);
}));
w('};');
const dst = path.resolve(root, 'test', 'test_suflet', 'palette_fixture.h');
fs.writeFileSync(dst, out.join('\n') + '\n');
console.log(`${designs.length * BODIES.length} palettes -> ${path.relative(root, dst)}`);
